def get_contextual_tips(query: str) -> list[str]:
    """Return a list of tip strings whose keywords match *query*."""
    q = query.lower()
    matched: list[str] = []
    seen: set[str] = set()
    for entry in _KNOWLEDGE:
        if any(kw in q for kw in entry["keywords"]):
            tip = entry["tip"]
            if tip not in seen:
                seen.add(tip)
                matched.append(tip)
    return matched


